from __future__ import annotations

"""Leon application sound events and playback helpers.

The default ``gentle`` pack is sourced from existing CC0 sounds on Wikimedia
Commons.  It is fetched lazily in a daemon thread and cached per user, so
normal startup never waits for the network.  Custom local audio overrides are
also supported; WAV uses QSoundEffect for the lowest latency and other common
formats use QMediaPlayer.
"""

import os
import sys
import threading
from pathlib import Path
from typing import Mapping
from urllib.request import Request, urlopen

SOUND_EVENTS = {
    "download_complete",
    "queue_complete",
    "error",
    "warning",
    "cancelled",
    "notification",
}

SOUND_THEMES = {
    "gentle": ("ملایم و دلنشین", "Gentle & pleasant"),
    "system": ("صدای سیستم", "System sounds (legacy)"),
}

# Existing 2.5.8 preferences transparently migrate to the new default pack.
LEGACY_SOUND_THEMES = {"minimal", "soft", "digital"}
DEFAULT_SOUND_THEME = "gentle"
DEFAULT_VOLUME = 58

SUPPORTED_CUSTOM_AUDIO = {".wav", ".ogg", ".oga", ".mp3", ".m4a", ".aac", ".flac"}

