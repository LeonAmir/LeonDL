GENTLE_EVENT_ASSET = {
    "download_complete": "happy_beep",
    "queue_complete": "success_piano",
    "notification": "happy_beep",
    "warning": "airplane_chime",
    "cancelled": "neutral_tone",
    "error": "neutral_tone",
}

# Keep warning/error/cancelled quieter than success notifications.  Error also
# plays slightly slower to distinguish it without using an abrasive buzzer.
EVENT_GAIN = {
    "download_complete": 0.92,
    "queue_complete": 0.88,
    "notification": 0.72,
    "warning": 0.70,
    "cancelled": 0.58,
    "error": 0.62,
}
EVENT_RATE = {
    "download_complete": 1.0,
    "queue_complete": 1.0,
    "notification": 1.0,
    "warning": 0.95,
    "cancelled": 0.92,
    "error": 0.82,
}


def normalize_sound_event(event: str) -> str:
    key = str(event or "").strip().lower()
    return key if key in SOUND_EVENTS else ""


def normalize_sound_theme(theme: str | None) -> str:
    key = str(theme or "").strip().lower()
    if key in LEGACY_SOUND_THEMES:
        return DEFAULT_SOUND_THEME
    return key if key in SOUND_THEMES else DEFAULT_SOUND_THEME


def application_root() -> Path:
    frozen_root = getattr(sys, "_MEIPASS", None)
    if frozen_root:
        return Path(str(frozen_root))
    return Path(__file__).resolve().parents[1]


def sound_cache_root() -> Path:
    override = str(os.environ.get("LEON_SOUND_CACHE_DIR") or "").strip()
    if override:
        return Path(override).expanduser()
    return Path.home() / ".yt_dlp_liquid" / "sounds" / "gentle"


def internet_sound_cache_path(asset_key: str) -> Path | None:
    asset = INTERNET_SOUND_ASSETS.get(str(asset_key or "").strip())
    if not asset:
        return None
    return sound_cache_root() / str(asset["filename"])


def _valid_ogg(path: Path, *, max_bytes: int) -> bool:
    try:
        size = path.stat().st_size
        if size < 256 or size > max_bytes:
            return False
        with path.open("rb") as handle:
            return handle.read(4) == b"OggS"
    except OSError:
        return False


def cached_internet_asset(asset_key: str) -> Path | None:
    asset = INTERNET_SOUND_ASSETS.get(str(asset_key or "").strip())
    path = internet_sound_cache_path(asset_key)
    if not asset or path is None:
        return None
    return path if _valid_ogg(path, max_bytes=int(asset["max_bytes"])) else None


def gentle_sound_path(event: str) -> Path | None:
    key = normalize_sound_event(event)
    if not key:
        return None
    asset_key = GENTLE_EVENT_ASSET.get(key, "")
    return cached_internet_asset(asset_key)


def resolve_sound_path(theme: str, event: str, custom_paths: Mapping[str, str] | None = None) -> Path | None:
    event_key = normalize_sound_event(event)
    if not event_key:
        return None
    if custom_paths:
        custom = str(custom_paths.get(event_key) or "").strip()
        if custom:
            path = Path(custom).expanduser()
            if path.is_file() and path.suffix.lower() in SUPPORTED_CUSTOM_AUDIO:
                return path
    theme_key = normalize_sound_theme(theme)
    if theme_key == "gentle":
        return gentle_sound_path(event_key)
    return None


def download_internet_sound_asset(asset_key: str, *, timeout: float = 12.0) -> Path | None:
    """Fetch one known CC0 sound atomically and validate the Ogg payload."""
    asset = INTERNET_SOUND_ASSETS.get(str(asset_key or "").strip())
    target = internet_sound_cache_path(asset_key)
    if not asset or target is None:
        return None
    max_bytes = int(asset["max_bytes"])
    if _valid_ogg(target, max_bytes=max_bytes):
        return target

    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_suffix(target.suffix + ".part")
    request = Request(
        str(asset["download_url"]),
        headers={"User-Agent": "LeonDL-SoundFetcher/1.0"},
    )
    try:
        with urlopen(request, timeout=max(1.0, float(timeout))) as response:
            payload = response.read(max_bytes + 1)
        if len(payload) > max_bytes or len(payload) < 256 or not payload.startswith(b"OggS"):
            return None
        temp.write_bytes(payload)
        os.replace(temp, target)
        return target if _valid_ogg(target, max_bytes=max_bytes) else None
    except Exception:
        return None
    finally:
        try:
            temp.unlink(missing_ok=True)
        except OSError:
            pass


def prepare_gentle_sound_pack() -> dict[str, Path]:
    """Download/cache all unique sounds used by the Gentle theme."""
    prepared: dict[str, Path] = {}
    for asset_key in dict.fromkeys(GENTLE_EVENT_ASSET.values()):
        path = download_internet_sound_asset(asset_key)
        if path is not None:
            prepared[asset_key] = path
    return prepared


def gentle_pack_ready() -> bool:
    return all(cached_internet_asset(key) is not None for key in set(GENTLE_EVENT_ASSET.values()))


def play_system_sound(event: str) -> bool:
    """Legacy system-sound path used only when System Sounds is selected."""
    key = normalize_sound_event(event)
    if not key or os.name != "nt":
        return False
    try:
        import winsound

        success_like = {"download_complete", "queue_complete", "notification"}
        if key in success_like:
            flag = winsound.MB_ICONASTERISK
        elif key == "error":
            flag = winsound.MB_ICONHAND
        else:
            flag = winsound.MB_ICONEXCLAMATION
        winsound.MessageBeep(flag)
        return True
    except Exception:
        return False


class SoundEventPlayer:
    """Low-overhead sound player with a lazily cached internet Gentle pack."""

    def __init__(self, parent=None) -> None:
        self.parent = parent
        self.theme = DEFAULT_SOUND_THEME
        self.volume = DEFAULT_VOLUME
        self.custom_paths: dict[str, str] = {}
        self._effects: dict[str, object] = {}
        self._media_players: dict[str, object] = {}
        self._audio_outputs: dict[str, object] = {}
        self._sources: dict[str, str] = {}
        self._qt_available: bool | None = None
        self._prepare_lock = threading.Lock()
        self._prepare_thread: threading.Thread | None = None
        self._prepare_failed = False

    def configure(
        self,
        *,
        theme: str | None = None,
        volume: int | float | None = None,
        custom_paths: Mapping[str, str] | None = None,
    ) -> None:
        if theme is not None:
            self.theme = normalize_sound_theme(theme)
        if volume is not None:
            try:
                self.volume = max(0, min(100, int(float(volume))))
            except (TypeError, ValueError):
                self.volume = DEFAULT_VOLUME
        if custom_paths is not None:
            self.custom_paths = {
                key: str(value or "").strip()
                for key, value in custom_paths.items()
                if normalize_sound_event(key)
            }
        if self.theme == "gentle" and not gentle_pack_ready():
            self._start_prepare_thread()
        self._preload()

    def _start_prepare_thread(self) -> None:
        with self._prepare_lock:
            if self._prepare_thread is not None and self._prepare_thread.is_alive():
                return
            self._prepare_failed = False

            def worker() -> None:
                result = prepare_gentle_sound_pack()
                self._prepare_failed = len(result) < len(set(GENTLE_EVENT_ASSET.values()))

            self._prepare_thread = threading.Thread(target=worker, name="leon-sound-cache", daemon=True)
            self._prepare_thread.start()

    def is_preparing(self) -> bool:
        return bool(self._prepare_thread is not None and self._prepare_thread.is_alive())

    def gentle_ready(self) -> bool:
        return gentle_pack_ready()

    def prepare_gentle(self) -> None:
        self._start_prepare_thread()

    def _qt_classes(self):
        if self._qt_available is False:
            return None
        try:
            from PySide6.QtCore import QUrl
            from PySide6.QtMultimedia import QAudioOutput, QMediaPlayer, QSoundEffect
        except Exception:
            self._qt_available = False
            return None
        self._qt_available = True
        return QUrl, QSoundEffect, QMediaPlayer, QAudioOutput

    def _event_volume(self, event: str) -> float:
        gain = float(EVENT_GAIN.get(event, 1.0))
        return max(0.0, min(1.0, (self.volume / 100.0) * gain))

    def _preload(self) -> None:
        if self.theme == "system":
            return
        classes = self._qt_classes()
        if classes is None:
            return
        QUrl, QSoundEffect, QMediaPlayer, QAudioOutput = classes
        for event in SOUND_EVENTS:
            path = resolve_sound_path(self.theme, event, self.custom_paths)
            source = str(path.resolve()) if path else ""
            if not source:
                continue
            if self._sources.get(event) == source:
                # Keep volume in sync even when source is unchanged.
                effect = self._effects.get(event)
                if effect is not None:
                    effect.setVolume(self._event_volume(event))
                output = self._audio_outputs.get(event)
                if output is not None:
                    output.setVolume(self._event_volume(event))
                continue

            suffix = path.suffix.lower()
            if suffix == ".wav":
                effect = self._effects.get(event)
                if effect is None:
                    effect = QSoundEffect(self.parent)
                    self._effects[event] = effect
                effect.setSource(QUrl.fromLocalFile(source))
                effect.setVolume(self._event_volume(event))
            else:
                player = self._media_players.get(event)
                output = self._audio_outputs.get(event)
                if player is None or output is None:
                    player = QMediaPlayer(self.parent)
                    output = QAudioOutput(self.parent)
                    player.setAudioOutput(output)
                    self._media_players[event] = player
                    self._audio_outputs[event] = output
                player.setSource(QUrl.fromLocalFile(source))
                player.setPlaybackRate(float(EVENT_RATE.get(event, 1.0)))
                output.setVolume(self._event_volume(event))
            self._sources[event] = source

    def play(self, event: str) -> bool:
        key = normalize_sound_event(event)
        if not key:
            return False
        if self.theme == "system":
            return play_system_sound(key)
        if self.theme == "gentle" and resolve_sound_path(self.theme, key, self.custom_paths) is None:
            self._start_prepare_thread()
            return False

        self._preload()
        effect = self._effects.get(key)
        if effect is not None and self._sources.get(key, "").lower().endswith(".wav"):
            try:
                effect.setVolume(self._event_volume(key))
                if effect.isPlaying():
                    effect.stop()
                effect.play()
                return True
            except Exception:
                return False

        player = self._media_players.get(key)
        output = self._audio_outputs.get(key)
        if player is None or output is None:
            return False
        try:
            output.setVolume(self._event_volume(key))
            player.setPlaybackRate(float(EVENT_RATE.get(key, 1.0)))
            player.setPosition(0)
            player.play()
            return True
        except Exception:
            return False
